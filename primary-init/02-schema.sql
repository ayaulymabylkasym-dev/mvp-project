CREATE TABLE users (
  id BIGSERIAL PRIMARY KEY,
  email VARCHAR(160) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  full_name VARCHAR(120) NOT NULL,
  role VARCHAR(16) NOT NULL DEFAULT 'user'
    CHECK (role IN ('user','admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id BIGSERIAL PRIMARY KEY,
  slug VARCHAR(140) UNIQUE NOT NULL,
  name VARCHAR(140) NOT NULL,
  summary VARCHAR(300) NOT NULL,
  description TEXT NOT NULL,
  price NUMERIC(12,2),
  image_url TEXT,
  features TEXT NOT NULL DEFAULT '',
  audience VARCHAR(240) NOT NULL DEFAULT '',
  price_model VARCHAR(120) NOT NULL DEFAULT '',
  contact VARCHAR(160) NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE survey_responses (
  id BIGSERIAL PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  intent VARCHAR(40) NOT NULL,
  comment TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE offices (
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  address VARCHAR(240) NOT NULL,
  latitude NUMERIC(9,6) NOT NULL,
  longitude NUMERIC(9,6) NOT NULL,
  phone VARCHAR(40),
  email VARCHAR(160)
);

CREATE INDEX idx_survey_product ON survey_responses (product_id);
CREATE INDEX idx_survey_user ON survey_responses (user_id);

